/** 보드 셀 값 (1-based 인덱스) */
export const PIECE_INDEX: Readonly<Record<PieceType, number>> = {
  I: 1,
  O: 2,
  T: 3,
  S: 4,
  Z: 5,
  J: 6,
  L: 7,
}

export const cellsOf = (type: PieceType, rot: Rotation): readonly Cell[] => PIECES[type][rot]!

export const rotateCw = (r: Rotation): Rotation => ((r + 1) % 4) as Rotation
export const rotateCcw = (r: Rotation): Rotation => ((r + 3) % 4) as Rotation
